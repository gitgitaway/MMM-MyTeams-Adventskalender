/**
 * Get translation for specified language and key
 * Falls back to English if language not found or key missing
 * @param {string} lang - Language code (e.g., 'en', 'de', 'fr')
 * @param {string} key - Translation key
 * @returns {string} Translated string or fallback to English
 */
function getTranslation(lang, key) {
    if (adventTranslations[lang] && adventTranslations[lang][key]) {
        return adventTranslations[lang][key];
    }

    if (adventTranslations.en && adventTranslations.en[key]) {
        return adventTranslations.en[key];
    }
    
    return key;
}

/**
 * Get all available languages
 * @returns {Object} Language map with codes and names
 */
function getAvailableLanguages() {
    const languages = {};
    for (const [code, strings] of Object.entries(adventTranslations)) {
        languages[code] = strings.language;
    }
    return languages;
}

